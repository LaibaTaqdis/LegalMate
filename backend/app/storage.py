"""Private file storage for the Legal Vault (Supabase Storage over HTTP, with the server-side service key).

The bucket is PRIVATE: nothing in it can be read without a signed link, and a link is made only after the caller proved the file is
theirs and lives for a few minutes. Object names are generated by us (`<user id>/<random id>.<ext>`), never taken from the user.
"""
from __future__ import annotations

import logging
from urllib.parse import quote

import httpx

log = logging.getLogger("legalmate.storage")


class StorageError(Exception):
    """The storage service refused or could not be reached. The message is for the server log, not for the user."""


class Storage:
    def __init__(self, base_url: str, service_key: str, bucket: str, *, timeout: float = 60.0):
        self.base, self.bucket = base_url.rstrip("/") + "/storage/v1", bucket
        self._headers = {"apikey": service_key, "Authorization": f"Bearer {service_key}"}
        self._client = httpx.Client(timeout=timeout)

    def _req(self, method: str, path: str, **kw) -> httpx.Response:
        try:
            r = self._client.request(method, self.base + path, headers={**self._headers, **kw.pop("headers", {})}, **kw)
        except httpx.HTTPError as e:
            raise StorageError(f"{method} {path}: {type(e).__name__}: {e}") from e
        return r

    def ensure_bucket(self, max_bytes: int) -> None:
        """Creates the private bucket if it does not exist yet (an existing one is left as it is)."""
        r = self._req("GET", f"/bucket/{self.bucket}")
        if r.status_code == 200:
            return
        r = self._req("POST", "/bucket", json={"id": self.bucket, "name": self.bucket, "public": False, "file_size_limit": max_bytes})
        if r.status_code not in (200, 201, 409):
            raise StorageError(f"could not create bucket {self.bucket}: {r.status_code} {r.text[:200]}")

    def upload(self, path: str, data: bytes, content_type: str) -> None:
        r = self._req("POST", f"/object/{self.bucket}/{quote(path)}", content=data, headers={"Content-Type": content_type, "x-upsert": "false"})
        if r.status_code not in (200, 201):
            raise StorageError(f"upload {path}: {r.status_code} {r.text[:200]}")

    def signed_url(self, path: str, seconds: int, download_name: str | None = None) -> str:
        r = self._req("POST", f"/object/sign/{self.bucket}/{quote(path)}", json={"expiresIn": seconds})
        if r.status_code != 200:
            raise StorageError(f"sign {path}: {r.status_code} {r.text[:200]}")
        signed = r.json().get("signedURL") or r.json().get("signedUrl") or ""
        url = signed if signed.startswith("http") else self.base + signed
        if download_name is not None:                                                    # makes the browser save it under this name
            url += "&download=" + quote(download_name, safe="")
        return url

    def delete(self, paths: list[str]) -> None:
        if not paths:
            return
        r = self._req("DELETE", f"/object/{self.bucket}", json={"prefixes": paths})
        if r.status_code not in (200, 204):
            raise StorageError(f"delete {len(paths)} object(s): {r.status_code} {r.text[:200]}")

    def close(self) -> None:
        self._client.close()


def build_storage(settings) -> Storage | None:
    """The real storage, or None when no Supabase URL and key are set (the Vault's file part then says it is not available)."""
    if not settings.supabase_url or not settings.supabase_service_key:
        return None
    st = Storage(settings.supabase_url, settings.supabase_service_key, settings.vault_bucket)
    try:
        st.ensure_bucket(settings.docs.max_upload_bytes + 1024 * 1024)
    except StorageError:
        log.warning("Supabase Storage is not reachable; Vault files will say they are unavailable until it is", exc_info=True)
    return st
