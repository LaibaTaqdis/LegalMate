"""Stage 4 - corpus QA report (reports/corpus_qa.md + reports/corpus_qa.json).

Answers: what is in the knowledge base, what was repaired, what is uncertain, what is missing.
Run:  python -m ingest.s4_qa
"""
from __future__ import annotations

import csv
import difflib
import html
import json
import random
import re
import statistics
import sys
import zipfile
from collections import Counter

from .config import CHECKLIST_XLSX, CURATED_CSV, INTERIM_DIR, PROCESSED_DIR, REPORTS_DIR
from .s2_manifest import base_name, norm_key

CHECKLIST = CHECKLIST_XLSX


def read_checklist() -> list[dict]:
    """Minimal .xlsx reader (stdlib only): Federal + Punjab sheets -> [{name, year, priority, module, scope}]"""
    if not CHECKLIST.exists():
        return []
    z = zipfile.ZipFile(CHECKLIST)
    ss = [html.unescape("".join(re.findall(r"<t[^>]*>(.*?)</t>", si, re.S)))
          for si in re.findall(r"<si>(.*?)</si>", z.read("xl/sharedStrings.xml").decode(), re.S)]
    out = []
    for sheet, scope in (("xl/worksheets/sheet2.xml", "Federal"), ("xl/worksheets/sheet3.xml", "Punjab")):
        x = z.read(sheet).decode()
        for row in re.findall(r"<row [^>]*>(.*?)</row>", x, re.S)[1:]:
            cells = {}
            for m in re.finditer(r'<c r="([A-Z]+)\d+"([^>]*?)(?:/>|>(.*?)</c>)', row, re.S):
                col, attrs, inner = m.groups()
                if not inner:
                    continue
                v = re.search(r"<v>(.*?)</v>", inner, re.S)
                if not v:
                    continue
                cells[col] = ss[int(v.group(1))] if 't="s"' in attrs else v.group(1)
            if cells.get("B"):
                out.append({"name": cells["B"], "year": cells.get("C", ""), "scope": scope,
                            "priority": cells.get("F" if scope == "Federal" else "F", ""),
                            "module": cells.get("E", "")})
    return out


def match_checklist(items: list[dict], docs: list[dict]) -> list[dict]:
    res = []
    live = [d for d in docs if not d["duplicate_of"] and not d["is_amendment"]]   # a base law, never its amendment
    for it in items:
        name = it["name"].replace("NADRA", "National Database and Registration Authority")
        name = re.sub(r"\bas amended in Punjab\b", "", name, flags=re.I)
        name = re.sub(r"\([A-Z]{2,6}\)", "", name)                        # "(CPC)", "(PPC)"
        name = re.sub(r"\(.*?(arts?|fundamental).*?\)", "", name, flags=re.I)
        want = base_name(name + " Act")
        year = int(it["year"]) if str(it["year"]).isdigit() else None
        best, best_s = None, 0.0
        for d in live:
            have = base_name(d["title"])
            s = difflib.SequenceMatcher(None, want, have).ratio()
            if want and (want in have or have in want) and min(len(want), len(have)) >= 8:
                s = max(s, 0.88)
            if year and d["year"] == year:
                s += 0.05
            if s > best_s:
                best, best_s = d, s
        found = best is not None and best_s >= 0.84
        res.append({**it, "found": found, "match": best["title"] if found else "", "score": round(best_s, 2),
                    "jurisdiction": best["jurisdiction"] if found else ""})
    return res


def main() -> None:
    man = json.loads((INTERIM_DIR / "manifest.json").read_text(encoding="utf-8"))
    docs = man["docs"]
    D = {d["doc_id"]: d for d in docs}
    stats = json.loads((INTERIM_DIR / "parse_stats.json").read_text(encoding="utf-8"))
    chunks = [json.loads(l) for l in open(PROCESSED_DIR / "chunks.jsonl", encoding="utf-8")]
    live = [d for d in docs if not d["duplicate_of"]]
    L = [c["n_chars"] for c in chunks]
    rep = Counter()
    for d in docs:
        rep.update(d["clean_stats"])

    out = ["# LegalMate corpus QA report", "", "_Generated by `python -m ingest.s4_qa`. Nothing here verifies that a law is *currently in force*: "
           "the source dataset marks 45/47 curated records `UNVERIFIED` and gazette amendments are not merged into base texts._", ""]

    out += ["## 1. Corpus summary", "",
            f"- PDFs ingested: **{len(docs)}** | unique laws after de-duplication: **{len(live)}** | duplicates folded: {len(docs) - len(live)}",
            f"- Chunks: **{len(chunks):,}** | total text: {sum(L) / 1e6:.1f}M chars (~{sum(L) / 4e6:.1f}M tokens) | "
            f"chunk size p10/median/p90: {sorted(L)[len(L) // 10]}/{int(statistics.median(L))}/{sorted(L)[9 * len(L) // 10]} chars",
            f"- Source tier: {dict(Counter(d['tier'] for d in live))}",
            f"- Jurisdiction: {dict(Counter(d['jurisdiction'] for d in live))}",
            f"- Instrument type: {dict(Counter(d['doc_type'] for d in live))}",
            f"- Chunk unit types: {dict(Counter(c['unit_type'] for c in chunks))}", ""]

    out += ["## 2. Cleaning (repairs applied across all documents)", ""]
    for k, v in sorted(rep.items(), key=lambda kv: -kv[1]):
        out.append(f"- `{k}`: {v:,}")
    ocr = sum(len(json.loads(f.read_text(encoding="utf-8")).get("ocr_pages", [])) for f in (INTERIM_DIR.parent / "extract").glob("*.json"))
    out += [f"- OCR'd image-only pages: {ocr}", ""]

    out += ["## 3. Titles: filename vs content", "",
            f"- Title decided by: {dict(Counter(d['title_source'] for d in docs))}", "",
            "**Conflicts to eyeball** (filename and content disagree, content chosen):", ""]
    for d in docs:
        if d["title_source"] == "content-conflict":
            out.append(f"- `{d['filename']}` → **{d['title']}** ({d['n_pages']} pp)")
    out.append("")

    out += ["## 4. Duplicates and variants", "", "**Folded as duplicates** (same text, kept highest-trust copy):", ""]
    for d in docs:
        if d["duplicate_of"]:
            out.append(f"- `{d['paths'][0]}` ≡ kept `{d.get('kept_path', '?')}`")
    out += ["", "**Kept as separate variants** (same law, different text: e.g. Punjab Code vs Federal copy; Jaccard 0.6-0.97):", ""]
    for p in man["pair_log"]:
        if p["action"] == "variant":
            out.append(f"- {p['jaccard']:.2f}  {D[p['a']]['title']} [{D[p['a']]['jurisdiction']}] ~ {D[p['b']]['title']} [{D[p['b']]['jurisdiction']}]")
    out.append("")

    out += ["## 5. Legal status and amendments", "",
            f"- Marked repealed: {[d['title'] for d in live if d['legal_status'] == 'repealed']}",
            f"- Gazette amendments / repeals found: {sum(d['is_amendment'] for d in live)}; linked to a base law in the corpus: "
            f"{sum(bool(d['amends']) for d in live)}", "",
            "**Amending instruments whose base law is NOT in the corpus** (the chatbot only has the amendment text):", ""]
    for i in man["unresolved_amendments"]:
        out.append(f"- {D[i]['title']}")
    out.append("")

    out += ["**Amendment links by fuzzy name (score < 0.97: please eyeball):**", ""]
    for d in live:
        if d["amends"] and d.get("link_score", 1) < 0.97:
            out.append(f"- {d['title']} -> {D[d['amends'][0]]['title']} (score {d['link_score']})")
    out.append("")

    out += ["## 6. Structure parsing", ""]
    structured = [s for s in stats.values() if s["structured"]]
    cov = [s["coverage"] for s in structured]
    out += [f"- Structured (section-aware): **{len(structured)}** docs | fallback paragraph windows: **{len(stats) - len(structured)}** docs "
            f"(mostly 1-6 page gazette amendments)",
            f"- Coverage (text captured in sections / total text): median {statistics.median(cov):.3f}; docs below 0.85: {sum(c < 0.85 for c in cov)}",
            f"- Duplicate section labels within a run (false-header signal): {sum(s['duplicate_labels'] > 0 for s in stats.values())} docs",
            "", "**Major laws, parse summary:**", "", "| Law | units | chunks | coverage | first..last |", "|---|---|---|---|---|"]
    for key in ("Pakistan Penal Code", "Code of Criminal Procedure", "Code of Civil Procedure", "Constitution of the Islamic",
                "Contract", "Qanun-e-Shahadat Order", "Punjab Rented Premises", "Islamabad Rent Restriction", "Punjab Labour Code",
                "Industrial Relations Act, 2012", "Prevention of Electronic Crimes Act", "Muslim Family Laws", "Dissolution of Muslim",
                "Family Court", "Punjab Protection of Women", "Protection Against Harassment", "Companies Act, 2017", "Punjab Consumer Protection", "Limitation Act"):
        for s in stats.values():
            if key in s["title"]:
                out.append(f"| {s['title'][:52]} | {s['units']} | {s['chunks']} | {s['coverage']:.2f} | {s['nums'][0]}..{s['nums'][-1]} |")
                break
    out += ["", "**Low-coverage documents** (<0.85; usually short Acts where title/enactment/schedule text is not a section):", ""]
    for s in sorted(structured, key=lambda s: s["coverage"])[:15]:
        if s["coverage"] < 0.85:
            out.append(f"- {s['coverage']:.2f}  {s['title']}")
    out.append("")

    out += ["## 7. Coverage against the team's law checklist (LegalMate_Law_Checklist_v2.xlsx)", ""]
    items = read_checklist()
    if items:
        res = match_checklist(items, docs)
        for pr in ("P1", "P2", "P3"):
            sub = [r for r in res if r["priority"] == pr]
            out.append(f"- **{pr}**: {sum(r['found'] for r in sub)}/{len(sub)} present")
        out += ["", "**Missing from the corpus (by priority):**", ""]
        for r in sorted(res, key=lambda r: r["priority"]):
            if not r["found"]:
                out.append(f"- {r['priority']} [{r['scope']}] {r['name']} ({r['year']}), module: {r['module']}  _(closest: {r['score']})_")
        out.append("")
        json.dump(res, open(REPORTS_DIR / "checklist_match.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    out += ["## 8. Extraction cross-check against the curated CSV", ""]
    if CURATED_CSV.exists():
        csv.field_size_limit(10**9)
        ratios = []
        for r in csv.DictReader(open(CURATED_CSV, encoding="utf-8-sig", newline="")):
            f = r["original_pdf_filename"].lower()
            d = next((x for x in docs if x["filename"].lower() == f or x["filename"].lower().replace(".pdf", "") == f), None)
            if d:
                pj = json.loads((INTERIM_DIR / "paras" / f"{d['doc_id']}.json").read_text(encoding="utf-8"))
                mine = len(re.sub(r"\s+", "", "".join(p[0] for p in pj["paras"])))
                ratios.append((len(re.sub(r"\s+", "", r["full_text"])), mine, d["title"]))
        rs = [b / a for a, b, _ in ratios if a]
        out += [f"- {len(ratios)}/47 curated records matched. Cleaned-text length / CSV-text length: median {statistics.median(rs):.2f}, "
                f"range {min(rs):.2f}-{max(rs):.2f} (expected < 1.0 because headers/footnotes/page numbers are stripped; "
                f"values far below ~0.85 deserve a look)", ""]
        for a, b, t in sorted(ratios, key=lambda x: x[1] / max(x[0], 1))[:5]:
            out.append(f"  - lowest: {t} ({b / max(a, 1):.2f})")
        out.append("")

    random.seed(7)
    out += ["## 9. Random chunk samples (read these!)", ""]
    for c in random.sample(chunks, 8):
        out += [f"**{c['header']}** (pp {c['page_start']}-{c['page_end']}, {c['n_chars']} chars, {c['jurisdiction']}/{c['tier']})", "",
                "> " + c["text"][:420].replace("\n", " ") + ("…" if c["n_chars"] > 420 else ""), ""]

    (REPORTS_DIR / "corpus_qa.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {REPORTS_DIR / 'corpus_qa.md'} ({len(out)} lines)")


if __name__ == "__main__":
    sys.exit(main())
